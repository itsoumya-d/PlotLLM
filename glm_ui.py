import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
import io

from glm_chat import assistant_response, check_service

# Set up Streamlit page
st.set_page_config(page_title="PlotLLM: AI Plot Generator with GLM", layout="wide")

# Disclaimer
@st.dialog("Disclaimer")
def disclaimer():
    st.write("This demo uses your GLM 4.5 subscription via ZAI to generate code based on your prompts. Please note that this software is a proof of concept and should not be used in production as it contains several security vulnerabilities. For example, code generated by GLM is automatically executed, which could lead to arbitrary code execution when exploiting user prompts. By using this demo, you agree that you are aware of this and proceed at your own risk.")
    st.write("The app uses your existing GLM API key from OpenCode configuration. Make sure your ZAI subscription is active.")
    if st.button("I understand"):
        st.session_state.accept_disc = True
        st.rerun()

if "accept_disc" not in st.session_state:
    disclaimer()

st.title("📊 PlotLLM: AI Plot Generator with GLM 4.5")
st.markdown("Powered by your **ZAI GLM 4.5 subscription** 🚀")

# Settings
with st.sidebar.expander("⚙️ Settings"):
    reset_btn = st.button("🗑️ Reset Chat History")
    model_select = st.selectbox("Select GLM Model", [
        "glm-4.5",
        "glm-4.5-air",
        "glm-4.5-flash",
        "glm-4.5v"
    ])
    
    model_descriptions = {
        "glm-4.5": "Most capable model with best reasoning",
        "glm-4.5-air": "Lightweight version for quick responses",
        "glm-4.5-flash": "Fast model optimized for speed",
        "glm-4.5v": "Vision-enabled model (for image inputs)"
    }
    
    st.write(f"📝 {model_descriptions[model_select]}")

if reset_btn:
    st.session_state["messages"] = []
    st.session_state["response_code"] = ""

# Sidebar for file upload
st.sidebar.header("Output")

# Initialize session state for chat history
if "messages" not in st.session_state:
    st.session_state["messages"] = []

# Initialize session state for code
if "response_code" not in st.session_state:
    st.session_state["response_code"] = ""

# User query input
user_input = st.chat_input("Describe the plot you want to create")

if user_input:
    # Check if GLM service is available
    if not check_service():
        st.toast("GLM API credentials could not be found. Please make sure your OpenCode GLM setup is configured correctly.", icon="🚨")
    else:
        st.session_state["messages"].append({"role": "user", "content": user_input})

        # Use GLM to generate Matplotlib code
        response_text, response_code = assistant_response(user_input, st.session_state["messages"], model=model_select)

        st.session_state["messages"].append({"role": "assistant", "content": response_text})
        st.session_state["response_code"] = response_code

# Display chat history
for message in st.session_state["messages"]:
    st.chat_message(message["role"]).write(message["content"])

# Display generated code
st.sidebar.subheader("📝 Generated Python Code")
if "response_code" in st.session_state and len(st.session_state["response_code"]) >= 1:
    code = st.session_state["response_code"]
    st.sidebar.code(code, language="python")
    st.sidebar.button("Copy Code", on_click=lambda: st.session_state.update({"copy_code": code}))

# Execute generated code and show plot
st.sidebar.subheader("📊 Generated Plot")
if "response_code" in st.session_state and len(st.session_state["response_code"]) >= 1:
    code_to_run = st.session_state["response_code"]
    try:
        # Create a clean environment for code execution
        exec_globals = {
            'plt': plt,
            'np': np,
            'pd': pd,
            'matplotlib': plt.matplotlib,
            'numpy': np,
            'pandas': pd
        }
        exec(code_to_run, exec_globals)
        st.sidebar.pyplot()
        
    except Exception as e:
        st.sidebar.error(f"Error executing code: {e}")
        st.sidebar.code(f"Error details: {str(e)}", language="text")